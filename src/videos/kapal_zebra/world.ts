// The whole world as one three.js scene: sky, sun, clouds that travel with the lens, the sea (the bridge river shader
// over 9 km, its level animated per shot), the Simeulue coast (island.ts) and the cast / effect cards (cast.ts).
// update(id, f, camera) is a pure function of id + f.
